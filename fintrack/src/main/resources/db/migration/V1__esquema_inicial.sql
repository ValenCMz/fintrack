-- Esquema base de FinTrack, tal como quedo antes de la Fase B (modelo completo
-- de tarjetas). Refleja el estado que Hibernate habia generado con
-- ddl-auto=update, incluido el account.owner nullable que se aplico a mano.
--
-- Los nombres de columna son los fisicos (snake_case): Spring aplica
-- CamelCaseToUnderscoresNamingStrategy a los @Column explicitos.

CREATE TABLE users (
    id       uuid NOT NULL,
    email    varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    rol      varchar(255),
    username varchar(255) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_rol_check CHECK (rol IN ('USER', 'ADMIN'))
);

CREATE TABLE account (
    id uuid NOT NULL,
    active boolean NOT NULL,
    name varchar(255) NOT NULL,
    owner varchar(255),
    type smallint NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT account_pkey PRIMARY KEY (id),
    CONSTRAINT account_type_check CHECK (type BETWEEN 0 AND 3),
    CONSTRAINT fk_account_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE category (
    id uuid NOT NULL,
    active boolean NOT NULL,
    color character varying(255) NOT NULL,
    name character varying(255) NOT NULL,
    type smallint NOT NULL,
    user_id uuid,
    CONSTRAINT category_pkey PRIMARY KEY (id),
    CONSTRAINT category_type_check CHECK (type >= 0 AND type <= 1),
    CONSTRAINT fk_category_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- Modelo viejo de tarjeta: due_day (fecha) + amount. Se reemplaza en V2.
CREATE TABLE card (
    id uuid NOT NULL,
    active boolean NOT NULL,
    amount numeric(38,2) NOT NULL,
    due_day date NOT NULL,
    holder_name character varying(255) NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT card_pkey PRIMARY KEY (id),
    CONSTRAINT fk_card_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE debt (
    id uuid NOT NULL,
    creditor character varying(255) NOT NULL,
    remaining_amount numeric(38,2) NOT NULL,
    start_date date NOT NULL,
    status smallint NOT NULL,
    total_amount numeric(38,2) NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT debt_pkey PRIMARY KEY (id),
    CONSTRAINT debt_status_check CHECK (status >= 0 AND status <= 1),
    CONSTRAINT fk_debt_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE fixed_expende (
    id uuid NOT NULL,
    active boolean NOT NULL,
    amount numeric(38,2) NOT NULL,
    due_day date NOT NULL,
    frequency character varying(255),
    name character varying(255) NOT NULL,
    account_id uuid NOT NULL,
    category_id uuid NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT fixed_expende_pkey PRIMARY KEY (id),
    CONSTRAINT fk_fixed_expende_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_fixed_expende_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT fk_fixed_expende_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE monotributo (
    id uuid NOT NULL,
    due_day date NOT NULL,
    monthly_amount numeric(38,2) NOT NULL,
    name character varying(255) NOT NULL,
    status smallint NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT monotributo_pkey PRIMARY KEY (id),
    CONSTRAINT monotributo_status_check CHECK (status >= 0 AND status <= 1),
    CONSTRAINT fk_monotributo_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE password_reset_token (
    token character varying(255) NOT NULL,
    email character varying(255) NOT NULL,
    expiration_time bigint NOT NULL,
    used boolean NOT NULL,
    CONSTRAINT password_reset_token_pkey PRIMARY KEY (token)
);

CREATE TABLE refresh_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fecha_expiracion timestamp(6) without time zone NOT NULL,
    hashed_token character varying(255) NOT NULL,
    revoked boolean NOT NULL,
    usuario_id uuid NOT NULL,
    CONSTRAINT refresh_token_pkey PRIMARY KEY (id),
    CONSTRAINT refresh_token_hashed_token_unique UNIQUE (hashed_token),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (usuario_id) REFERENCES users (id)
);

CREATE TABLE saving_goal (
    id uuid NOT NULL,
    active boolean NOT NULL,
    current_amount numeric(38,2) NOT NULL,
    name character varying(255) NOT NULL,
    target_amount numeric(38,2) NOT NULL,
    target_date date NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT saving_goal_pkey PRIMARY KEY (id),
    CONSTRAINT fk_saving_goal_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE "transaction" (
    id uuid NOT NULL,
    amount numeric(38,2) NOT NULL,
    date date NOT NULL,
    description character varying(255),
    notes character varying(255),
    type smallint NOT NULL,
    account_id uuid NOT NULL,
    category_id uuid NOT NULL,
    user_id uuid NOT NULL,
    CONSTRAINT transaction_pkey PRIMARY KEY (id),
    CONSTRAINT transaction_type_check CHECK (type >= 0 AND type <= 1),
    CONSTRAINT fk_transaction_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_transaction_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT fk_transaction_user FOREIGN KEY (user_id) REFERENCES users (id)
);
